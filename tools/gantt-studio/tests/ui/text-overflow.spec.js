import {test,expect} from '@playwright/test';
for(const compact of [false,true]) test('完整任务文本、可操作边界与可选截断 compact='+compact,async({page})=>{
 await page.goto('/');
 const title='这是一个需要完整显示而不能截断的很长任务名称 ABC 123'.repeat(2);
 await page.locator('[data-task="a"]').dblclick();
 await page.getByLabel('任务名称').fill(title);
 await page.getByRole('button',{name:'保存更改'}).click();
 if(compact) await page.locator('#compactMode').check();
 await expect(page.locator('#hideOverflowText')).not.toBeChecked();
 await expect(page.locator('[data-task="a"]')).toHaveCSS('overflow','visible');
 await expect(page.locator('[data-task="a"] strong')).toHaveCSS('pointer-events','none');
 const edge=page.locator('[data-task="a"] .handle.right');
 const r=await edge.boundingBox();
 expect(await page.evaluate(({x,y})=>document.elementFromPoint(x,y)?.classList.contains('handle'),{x:r.x+4,y:r.y+r.height/2})).toBe(true);
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('gantt-studio-v1')));
 const before=(await read()).tasks.find(t=>t.id==='a').end;
 await page.mouse.move(r.x+4,r.y+r.height/2);
 await page.mouse.down();
 await page.mouse.move(r.x+116,r.y+r.height/2,{steps:10});
 await page.mouse.up();
 expect((await read()).tasks.find(t=>t.id==='a').end).toBeGreaterThan(before);
 const svg=await page.evaluate(async()=>{const {projectSVG}=await import('/src/export.js');return projectSVG(JSON.parse(localStorage.getItem('gantt-studio-v1'))).svg;});
 expect(svg).toContain(title);
 expect(svg).not.toContain('<g clip-path=');
 await page.locator('#hideOverflowText').check();
 await expect(page.locator('[data-task="a"]')).toHaveCSS('overflow','hidden');
 await page.reload();
 await expect(page.locator('#hideOverflowText')).toBeChecked();
 const clipped=await page.evaluate(async()=>{const {projectSVG}=await import('/src/export.js');return projectSVG(JSON.parse(localStorage.getItem('gantt-studio-v1'))).svg;});
 expect(clipped).toContain('<g clip-path=');
 expect(clipped).not.toContain(title);
});
